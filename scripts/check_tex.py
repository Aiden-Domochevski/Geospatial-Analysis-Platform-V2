import re
with open(r"final_model\documentation\rapport.tex","r",encoding="utf-8") as f:
    content = f.read()
opens = content.count("{")
closes = content.count("}")
print(f"Braces: open={opens}, close={closes}, diff={opens-closes}")
print(f"Ends with end document: {content.strip().endswith(chr(92)+'end{document}')}")
chapters = len(re.findall(r"\\chapter\{", content))
sections = len(re.findall(r"\\section\{", content))
subsections = len(re.findall(r"\\subsection\{", content))
figures = len(re.findall(r"\\includegraphics", content))
tables = len(re.findall(r"\\begin\{table\}", content))
print(f"Chapters: {chapters}, Sections: {sections}, Subsections: {subsections}")
print(f"Figures: {figures}, Tables: {tables}")
print(f"Total chars: {len(content)}")
